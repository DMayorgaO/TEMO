import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {TransactionsService}=require('../backend/dist/modules/transactions/transactions.service');
const cash=(quantity)=>({independent:true,primaryDirection:'ENTRA',primaryCounts:{NIO:[{denomination:100,piles25:0,loose:quantity}],USD:[]},changeCounts:{NIO:[],USD:[]}});
let fail=false,rolledBack=false,committed=false,deferred=false;
let stored={a:cash(5),b:cash(3)}, applied=[];
const client={query:async(sql,args)=>{
  if(sql.includes('order by t.orden_grupo for update'))return {rows:[{id_transaccion:'a'},{id_transaccion:'b'}]};
  if(sql.includes('from temo.abonos_pendientes'))return {rowCount:0,rows:[]};
  if(sql.includes('set_config'))deferred=sql.includes("'on'");
  return {rows:[],rowCount:0};
}};
const db={transaction:async fn=>{const snapshot=structuredClone(stored);try{const result=await fn(client);committed=true;return result;}catch(e){stored=snapshot;rolledBack=true;throw e;}}};
const service=new TransactionsService(db);
service.loadEditableTransaction=async()=>({id_grupo_transacciones:'g',id_turno:'s',estado_turno:'ABIERTO'});
service.loadStoredSettlement=async(_c,_g,id)=>stored[id];
service.update=async(id,_data,_u,c)=>{assert.equal(c,client);assert.equal(deferred,true);stored[id]=cash(7);if(fail)throw Error('validation');};
service.void=async(id,_u,c)=>{assert.equal(c,client);assert.equal(deferred,true);delete stored[id];};
service.applySettlementDeltaToCurrentCashCount=async(_c,_s,before,after,reject)=>{assert.equal(deferred,false);assert.equal(reject,true);applied.push([before,after]);};
const input={updates:[{id:'a',data:{rates:{buy:36.4}}}],voidIds:['b'],preferential:false};
assert.deepEqual(await service.updateGroup('a',input,{}),{updated:1,voided:1});
assert.equal(committed,true);assert.equal(applied.length,1);
assert.equal(applied[0][0].primaryCounts.NIO[0].loose,8);
assert.equal(applied[0][1].primaryCounts.NIO[0].loose,7);
stored={a:cash(5),b:cash(3)}; fail=true; committed=false;
await assert.rejects(service.updateGroup('a',input,{}),/validation/);
assert.equal(rolledBack,true);assert.equal(committed,false);assert.equal(stored.a.primaryCounts.NIO[0].loose,5);
fail=false;
await assert.rejects(service.updateGroup('a',{...input,voidIds:['a']},{}),/grupo cambio/);
console.log('PASS: atomic group update, aggregate cash delta, rollback and duplicate IDs');
