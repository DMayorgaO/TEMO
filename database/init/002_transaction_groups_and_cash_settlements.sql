-- Los datos comunes del cliente y de la liquidacion viven una sola vez por grupo.
CREATE TABLE IF NOT EXISTS grupos_transacciones (
  id_grupo_transacciones UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo_operacion BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  id_turno UUID NOT NULL REFERENCES turnos(id_turno),
  id_contraparte UUID REFERENCES contrapartes(id_contraparte),
  estado estado_grupo_transacciones NOT NULL DEFAULT 'ABIERTO',
  id_tipo_cambio_vuelto UUID REFERENCES tipos_cambio(id_tipo_cambio),
  tipo_tasa_vuelto tipo_tasa_aplicada,
  tasa_vuelto_usada NUMERIC(14, 6) CHECK (tasa_vuelto_usada IS NULL OR tasa_vuelto_usada > 0),
  observaciones TEXT,
  id_usuario_creacion UUID NOT NULL REFERENCES usuarios(id_usuario),
  id_usuario_modificacion UUID REFERENCES usuarios(id_usuario),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_modificacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_grupos_tasa_vuelto CHECK (
    (tipo_tasa_vuelto IS NULL AND tasa_vuelto_usada IS NULL)
    OR (tipo_tasa_vuelto IS NOT NULL AND tasa_vuelto_usada IS NOT NULL)
  )
);

ALTER TABLE transacciones
  ADD COLUMN IF NOT EXISTS id_grupo_transacciones UUID,
  ADD COLUMN IF NOT EXISTS orden_grupo SMALLINT;

-- Cada transaccion historica se convierte en un grupo unitario sin cambiar su identidad.
INSERT INTO grupos_transacciones (
  id_grupo_transacciones,
  id_turno,
  id_contraparte,
  estado,
  id_usuario_creacion,
  id_usuario_modificacion,
  fecha_creacion,
  fecha_modificacion
)
SELECT
  t.id_transaccion,
  t.id_turno,
  t.id_contraparte,
  CASE
    WHEN t.estado = 'ANULADA' THEN 'ANULADO'::estado_grupo_transacciones
    ELSE 'COMPLETADO'::estado_grupo_transacciones
  END,
  t.id_usuario_creacion,
  t.id_usuario_modificacion,
  t.fecha_creacion,
  t.fecha_modificacion
FROM transacciones t
WHERE t.id_grupo_transacciones IS NULL
ON CONFLICT (id_grupo_transacciones) DO NOTHING;

UPDATE transacciones
SET id_grupo_transacciones = id_transaccion,
    orden_grupo = 1
WHERE id_grupo_transacciones IS NULL;

WITH ordenes_faltantes AS (
  SELECT
    id_transaccion,
    row_number() OVER (
      PARTITION BY id_grupo_transacciones
      ORDER BY fecha_transaccion, id_transaccion
    )::SMALLINT AS orden_calculado
  FROM transacciones
  WHERE orden_grupo IS NULL
)
UPDATE transacciones t
SET orden_grupo = o.orden_calculado
FROM ordenes_faltantes o
WHERE o.id_transaccion = t.id_transaccion;

DO $$ BEGIN
  ALTER TABLE transacciones
    ADD CONSTRAINT fk_transacciones_grupo
    FOREIGN KEY (id_grupo_transacciones)
    REFERENCES grupos_transacciones(id_grupo_transacciones);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

ALTER TABLE transacciones
  ALTER COLUMN id_grupo_transacciones SET NOT NULL,
  ALTER COLUMN orden_grupo SET NOT NULL;

DO $$ BEGIN
  ALTER TABLE transacciones
    ADD CONSTRAINT ck_transacciones_orden_grupo CHECK (orden_grupo > 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_transacciones_grupo_orden
  ON transacciones(id_grupo_transacciones, orden_grupo);

CREATE OR REPLACE FUNCTION validar_turno_grupo_transaccion()
RETURNS TRIGGER AS $$
DECLARE
  v_id_turno_grupo UUID;
BEGIN
  SELECT id_turno
  INTO v_id_turno_grupo
  FROM grupos_transacciones
  WHERE id_grupo_transacciones = NEW.id_grupo_transacciones;

  IF v_id_turno_grupo IS DISTINCT FROM NEW.id_turno THEN
    RAISE EXCEPTION
      'La transaccion y su grupo deben pertenecer al mismo turno';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validar_turno_grupo_transaccion ON transacciones;
CREATE TRIGGER trg_validar_turno_grupo_transaccion
BEFORE INSERT OR UPDATE OF id_turno, id_grupo_transacciones
ON transacciones
FOR EACH ROW
EXECUTE FUNCTION validar_turno_grupo_transaccion();

