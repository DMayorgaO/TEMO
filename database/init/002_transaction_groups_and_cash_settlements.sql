-- Vista operativa: una fila por grupo y moneda con recibido, entregado, vuelto y diferencia.
DROP VIEW IF EXISTS vw_grupos_transacciones_liquidacion;
CREATE OR REPLACE VIEW vw_grupos_transacciones_liquidacion AS
SELECT
  g.id_grupo_transacciones,
  g.codigo_operacion,
  g.id_turno,
  g.id_contraparte,
  g.estado,
  m.id_moneda,
  m.codigo AS codigo_moneda,
  m.simbolo,
  COALESCE(sum(a.monto_total) FILTER (WHERE a.tipo = 'TRANSACCION_RECIBIDO'), 0) AS monto_recibido,
  COALESCE(sum(a.monto_total) FILTER (WHERE a.tipo = 'TRANSACCION_ENTREGADO'), 0) AS monto_entregado,
  COALESCE(sum(a.monto_total) FILTER (WHERE a.tipo = 'TRANSACCION_VUELTO'), 0) AS monto_vuelto,
  COALESCE(sum(a.monto_esperado) FILTER (WHERE a.tipo = 'TRANSACCION_RECIBIDO'), 0) AS monto_esperado_recibido,
  COALESCE(sum(a.monto_esperado) FILTER (WHERE a.tipo = 'TRANSACCION_ENTREGADO'), 0) AS monto_esperado_entregado,
  COALESCE(sum(a.monto_esperado) FILTER (WHERE a.tipo = 'TRANSACCION_VUELTO'), 0) AS monto_esperado_vuelto,
  COALESCE(sum(a.diferencia) FILTER (WHERE a.tipo = 'TRANSACCION_RECIBIDO'), 0)
    - COALESCE(sum(a.diferencia) FILTER (WHERE a.tipo = 'TRANSACCION_ENTREGADO'), 0)
    - COALESCE(sum(a.diferencia) FILTER (WHERE a.tipo = 'TRANSACCION_VUELTO'), 0) AS diferencia,
  COALESCE(sum(a.monto_total) FILTER (WHERE a.tipo = 'TRANSACCION_RECIBIDO'), 0)
    - COALESCE(sum(a.monto_total) FILTER (WHERE a.tipo = 'TRANSACCION_ENTREGADO'), 0)
    - COALESCE(sum(a.monto_total) FILTER (WHERE a.tipo = 'TRANSACCION_VUELTO'), 0) AS monto_neto
FROM grupos_transacciones g
CROSS JOIN monedas m
LEFT JOIN arqueos a
  ON a.id_grupo_transacciones = g.id_grupo_transacciones
 AND a.id_moneda = m.id_moneda
GROUP BY
  g.id_grupo_transacciones,
  g.codigo_operacion,
  g.id_turno,
  g.id_contraparte,
  g.estado,
  m.id_moneda,
  m.codigo,
  m.simbolo;

COMMENT ON TABLE grupos_transacciones IS
  'Encabezado atomico para una o varias transacciones realizadas por el mismo cliente.';
COMMENT ON COLUMN arqueos.monto_total IS
  'Monto fisico contado; su tipo indica si fue recibido, entregado o devuelto.';
COMMENT ON COLUMN arqueos.monto_esperado IS
  'Monto calculado que se esperaba recibir o entregar antes del conteo fisico.';
COMMENT ON COLUMN arqueos.diferencia IS
  'Diferencia firmada entre monto fisico contado y monto esperado.';
COMMENT ON COLUMN arqueos_denominaciones.montones_25 IS
  'Cantidad de montones completos de 25 billetes o monedas.';
COMMENT ON COLUMN arqueos_denominaciones.sueltos IS
  'Cantidad de billetes o monedas fuera de los montones de 25.';
COMMENT ON COLUMN movimientos_efectivo.id_grupo_transacciones IS
  'Grupo que origino un movimiento de efectivo compartido entre varias transacciones.';
