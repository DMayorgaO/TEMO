CREATE OR REPLACE FUNCTION preparar_arqueo_denominacion()
RETURNS TRIGGER AS $$
DECLARE
  v_valor NUMERIC(14, 2);
  v_moneda_denominacion UUID;
  v_moneda_arqueo UUID;
BEGIN
  SELECT valor, id_moneda
  INTO v_valor, v_moneda_denominacion
  FROM denominaciones
  WHERE id_denominacion = NEW.id_denominacion;

  SELECT id_moneda
  INTO v_moneda_arqueo
  FROM arqueos
  WHERE id_arqueo = NEW.id_arqueo;

  IF v_moneda_denominacion IS DISTINCT FROM v_moneda_arqueo THEN
    RAISE EXCEPTION 'La denominacion y el arqueo deben pertenecer a la misma moneda';
  END IF;

  -- Compatibilidad con clientes antiguos que solo insertaban o actualizaban cantidad.
  IF TG_OP = 'UPDATE'
     AND NEW.montones_25 IS NOT DISTINCT FROM OLD.montones_25
     AND NEW.sueltos IS NOT DISTINCT FROM OLD.sueltos
     AND NEW.cantidad IS DISTINCT FROM OLD.cantidad THEN
    NEW.montones_25 = 0;
    NEW.sueltos = NEW.cantidad;
  ELSIF NEW.montones_25 = 0 AND NEW.sueltos = 0 AND NEW.cantidad > 0 THEN
    NEW.sueltos = NEW.cantidad;
  END IF;

  NEW.cantidad = NEW.montones_25 * 25 + NEW.sueltos;
  NEW.monto = NEW.cantidad * v_valor;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_preparar_arqueo_denominacion ON arqueos_denominaciones;
CREATE TRIGGER trg_preparar_arqueo_denominacion
BEFORE INSERT OR UPDATE OF id_arqueo, id_denominacion, montones_25, sueltos, cantidad
ON arqueos_denominaciones
FOR EACH ROW
EXECUTE FUNCTION preparar_arqueo_denominacion();

CREATE OR REPLACE FUNCTION recalcular_total_arqueo()
RETURNS TRIGGER AS $$
DECLARE
  v_id_arqueo UUID;
BEGIN
  v_id_arqueo := COALESCE(NEW.id_arqueo, OLD.id_arqueo);

  UPDATE arqueos
  SET monto_total = (
    SELECT COALESCE(sum(monto), 0)
    FROM arqueos_denominaciones
    WHERE id_arqueo = v_id_arqueo
  )
  WHERE id_arqueo = v_id_arqueo;

  IF TG_OP = 'UPDATE' AND OLD.id_arqueo IS DISTINCT FROM NEW.id_arqueo THEN
    UPDATE arqueos
    SET monto_total = (
      SELECT COALESCE(sum(monto), 0)
      FROM arqueos_denominaciones
      WHERE id_arqueo = OLD.id_arqueo
    )
    WHERE id_arqueo = OLD.id_arqueo;
  END IF;

  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_recalcular_total_arqueo ON arqueos_denominaciones;
CREATE TRIGGER trg_recalcular_total_arqueo
AFTER INSERT OR UPDATE OR DELETE
ON arqueos_denominaciones
FOR EACH ROW
EXECUTE FUNCTION recalcular_total_arqueo();

