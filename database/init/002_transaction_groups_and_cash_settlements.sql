-- Compatibilidad con instalaciones antiguas que guardaban una sola sucursal en la cuenta.
CREATE TABLE IF NOT EXISTS cuentas_sucursales (
  id_cuenta UUID NOT NULL
    REFERENCES cuentas_bancarias(id_cuenta) ON DELETE CASCADE,
  id_sucursal UUID NOT NULL
    REFERENCES sucursales(id_sucursal) ON DELETE CASCADE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (id_cuenta, id_sucursal)
);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'temo'
      AND table_name = 'cuentas_bancarias'
      AND column_name = 'id_sucursal'
  ) THEN
    EXECUTE '
      INSERT INTO cuentas_sucursales (id_cuenta, id_sucursal)
      SELECT id_cuenta, id_sucursal
      FROM cuentas_bancarias
      WHERE id_sucursal IS NOT NULL
      ON CONFLICT (id_cuenta, id_sucursal) DO NOTHING
    ';
  END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS idx_cuentas_sucursales_sucursal
  ON cuentas_sucursales(id_sucursal);

-- Compatibilidad con reglas fijas creadas antes de separar la moneda de comision.
